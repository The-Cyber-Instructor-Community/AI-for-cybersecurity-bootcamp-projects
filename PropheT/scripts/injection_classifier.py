"""T2: build the training lines, train the hidden-span instruction classifier, evaluate it, install it.

    python scripts/injection_classifier.py build     [--extra lines.csv]   -> data/t2/train.csv (+ manifest)
    python scripts/injection_classifier.py train     [--heldout payloads.txt] [--install]
    python scripts/injection_classifier.py evaluate  --heldout payloads.txt

Training lines are generated by code from templates (resume-styled instructions aimed at an AI screener, against
stuffed keyword lists and ordinary resume sentences), so no model output and no real resume is ever trained on.
--extra adds a CSV with columns text,label (label 1 = instruction) from a public dataset with a clear licence,
such as deepset/prompt-injections (Apache-2.0); record it in docs/SOURCES.md.

The held-out file is Darpan's own: instructions, a line "## data", then stuffed data and tricky benign resume
lines, written without looking at the regex patterns or these templates. The threshold is picked on a validation
split of the generated lines (the highest recall at a false-positive rate of at most 1%), never on the held-out
file; the held-out file reports recall on instructions and false alarms on the rest at that threshold, next to the
regex floor. --install writes chimera/resources/injection_classifier.json (plain JSON, scored by chimera/injection.py).
"""
