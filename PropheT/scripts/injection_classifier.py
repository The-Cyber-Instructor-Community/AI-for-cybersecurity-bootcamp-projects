def build_lines(seed: int, n_each: int) -> list[dict]:
    rng = random.Random(seed)
    rows = []
    for _ in range(n_each):
        o, a, c = rng.choice(OPENERS), rng.choice(ACTIONS), rng.choice(CLOSERS)
        text = " ".join(x for x in (o, a + c) if x).strip()
        if rng.random() < 0.3:                                   # two actions in one line
            text += " " + rng.choice(ACTIONS) + rng.choice(CLOSERS)
        rows.append({"text": text[0].upper() + text[1:], "label": 1, "kind": "instruction"})
    for _ in range(n_each):
        r = rng.random()
        if r < 0.45:
            text = " ".join(rng.sample(SKILLS, rng.randint(4, 14)))
        elif r < 0.6:
            text = " ".join(rng.sample(TITLES, rng.randint(3, 8)))
        elif r < 0.75:
            text = "Keywords: " + ", ".join(x.lower() for x in rng.sample(SKILLS, rng.randint(3, 9)))
        else:
            text = rng.choice(SENTENCES)
        rows.append({"text": text, "label": 0, "kind": "data" if r < 0.75 else "sentence"})
    rng.shuffle(rows)
    return rows


def read_heldout(path: Path) -> tuple[list[str], list[str]]:
    instructions, data, group = [], [], None
    for line in path.read_text(encoding="utf-8").splitlines():
        s = line.strip()
        if s.lower().startswith("## data"):
            group = data
        elif s and not s.startswith("#"):
            (instructions if group is None else data).append(s)
    return instructions, data


def cmd_build(args):
    rows = build_lines(args.seed, args.n)
    if args.extra:
        with open(args.extra, encoding="utf-8", newline="") as f:
            for r in csv.DictReader(f):
                rows.append({"text": r["text"].strip(), "label": int(r["label"]), "kind": f"extra:{args.extra.name}"})
    OUT.mkdir(parents=True, exist_ok=True)
    with open(OUT / "train.csv", "w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, fieldnames=["text", "label", "kind"])
        w.writeheader()
        w.writerows(rows)
    (OUT / "manifest.csv").write_text(
        "source,label,split,license\n"
        f"scripts/injection_classifier.py templates (seed {args.seed}),0 and 1,train+val,code-generated (repo licence)\n"
        + (f"{args.extra},0 and 1,train+val,see docs/SOURCES.md\n" if args.extra else ""), encoding="utf-8")
    print(f"{len(rows)} lines -> {OUT / 'train.csv'} ({sum(r['label'] for r in rows)} instructions)")


def fit(rows: list[dict], seed: int):
    rng = random.Random(seed)
    idx = list(range(len(rows)))
    rng.shuffle(idx)
    cut = int(0.8 * len(idx))
    train, val = [rows[i] for i in idx[:cut]], [rows[i] for i in idx[cut:]]
    vec = TfidfVectorizer(analyzer="char_wb", ngram_range=(2, 5), min_df=2, lowercase=True)
    x = vec.fit_transform([r["text"] for r in train])
    model = LogisticRegression(class_weight="balanced", C=2.0, max_iter=2000)
    model.fit(x, [r["label"] for r in train])
    p_val = model.predict_proba(vec.transform([r["text"] for r in val]))[:, 1]
    y_val = np.asarray([r["label"] for r in val])
    auc = roc_auc_score(y_val, p_val) if len(set(y_val)) > 1 else float("nan")
    neg = np.sort(p_val[y_val == 0])
    threshold = float(neg[int(np.ceil(0.99 * len(neg))) - 1]) + 1e-6 if len(neg) else 0.5   # FPR <= 1% on validation
    threshold = min(max(threshold, 0.5), 0.99)
    recall_val = float((p_val[y_val == 1] >= threshold).mean()) if (y_val == 1).any() else float("nan")
    return vec, model, threshold, {"val_auc": round(float(auc), 4), "val_recall_at_threshold": round(recall_val, 4),
                                   "train_lines": len(train), "val_lines": len(val)}


def evaluate(clf, heldout: Path) -> dict:
    instructions, data = read_heldout(heldout)
    p_i = [clf.score(t) for t in instructions]
    p_d = [clf.score(t) for t in data]
    regex_i = [bool(resume.find_patterns(t, resume.STRONG_PATTERNS + resume.WEAK_PATTERNS)) for t in instructions]
    regex_d = [bool(resume.find_patterns(t, resume.STRONG_PATTERNS + resume.WEAK_PATTERNS)) for t in data]
    either = [r or p >= clf.threshold for r, p in zip(regex_i, p_i)]
    either_d = [r or p >= clf.threshold for r, p in zip(regex_d, p_d)]
    res = {
        "heldout": str(heldout), "instructions": len(instructions), "others": len(data), "threshold": clf.threshold,
        "classifier_recall": sum(p >= clf.threshold for p in p_i) / max(len(p_i), 1),
        "classifier_false_alarms": sum(p >= clf.threshold for p in p_d),
        "regex_recall": sum(regex_i) / max(len(regex_i), 1), "regex_false_alarms": sum(regex_d),
        "regex_or_classifier_recall": sum(either) / max(len(either), 1), "regex_or_classifier_false_alarms": sum(either_d),
        "auc": roc_auc_score([1] * len(p_i) + [0] * len(p_d), p_i + p_d) if p_i and p_d else float("nan"),
    }
    res["missed_instructions"] = [t for t, p in zip(instructions, p_i) if p < clf.threshold and
                                  not resume.find_patterns(t, resume.STRONG_PATTERNS + resume.WEAK_PATTERNS)]
    res["false_alarm_lines"] = [t for t, p in zip(data, p_d) if p >= clf.threshold]
    return res


def cmd_train(args):
    with open(OUT / "train.csv", encoding="utf-8", newline="") as f:
        rows = [{"text": r["text"], "label": int(r["label"])} for r in csv.DictReader(f)]
    vec, model, threshold, stats = fit(rows, args.seed)
    stats.update({"seed": args.seed, "at": time.strftime("%Y-%m-%dT%H:%M:%S"), "features": len(vec.vocabulary_)})
    spec = injection.export(vec, model, threshold, stats)
    clf = injection.Classifier(spec)
    print(json.dumps(stats, indent=1))
    if args.heldout:
        res = evaluate(clf, args.heldout)
        print(json.dumps(res, indent=1))
        (OUT / "heldout_results.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    if args.install:
        injection.MODEL.write_text(json.dumps(spec), encoding="utf-8")
        injection.load.cache_clear()
        print(f"installed {injection.MODEL} ({injection.MODEL.stat().st_size // 1024} KB)")
    else:
        (OUT / "injection_classifier.json").write_text(json.dumps(spec), encoding="utf-8")
        print(f"wrote {OUT / 'injection_classifier.json'} (add --install to put it in chimera/resources/)")


def cmd_evaluate(args):
    clf = injection.load()
    if clf is None:
        sys.exit("no installed classifier (train --install first)")
    print(json.dumps(evaluate(clf, args.heldout), indent=1))


